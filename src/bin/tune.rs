//! SPSA evaluation tuning driver (Stage 5).
//!
//! Generates the dataset by deterministic self-play (baseline vs baseline at
//! a fixed depth — the same seed always yields the same games) or loads it
//! from files (`--data` text positions, `--pgn` game replays, optionally
//! seeded `--shuffle` and a `--test-split` holdout whose loss is reported
//! before *and* after tuning), runs the SPSA loop over the flat
//! [`EvalParams`] vector, writes checkpoint TOMLs at fixed iterations,
//! exports the best set found and finishes with a regression report
//! (tactics, `Threads = 1` determinism, eval deltas) of the tuned set
//! against the baseline so no known strength is silently lost.
//! `--compare A B` diffs two parameter files without tuning.
//!
//! Everything downstream of the seed is deterministic: same `--seed` →
//! identical dataset, identical SPSA trajectory, identical checkpoint and
//! export files.
//!
//! Usage:
//! ```text
//! tune [--seed N] [--iterations N] [--subset a,b,c]
//!      [--games N] [--depth N] [--in baseline.toml] [--out tuned.toml]
//!      [--data FILE] [--pgn FILE] [--shuffle] [--test-split F]
//!      [--checkpoint-every N] [--checkpoints-dir DIR]
//!      [--gain F] [--perturbation F] [--smoke]
//! tune --compare A B
//! ```

use std::fs;

use anyhow::{Context, bail};

use morstilia::book::SplitMix64;
use morstilia::evaluation::EvalParams;
use morstilia::regression::run_regression;
use morstilia::selfplay::{SelfPlayConfig, play_game_with};
use morstilia::tuning::dataset::DataSet;
use morstilia::tuning::{ParamSubset, SpsaConfig, tune_with_callback};

const USAGE: &str = "\
Morstilia — SPSA evaluation tuning.

Usage:
  tune [options]
  tune --compare A B

Options:
  --seed N             dataset + SPSA seed (default 1; full reproducibility)
  --games N            self-play games for the dataset (default 8, depth 4)
  --depth N            fixed search depth per dataset game (default 4)
  --data FILE          load positions from a `result FEN` / `FEN result`
                       text file instead of generating self-play games
                       (may be repeated)
  --pgn FILE           load every finished game of a PGN file (SAN plies
                       replayed; may be repeated, combinable with --data)
  --dump-data FILE     write the full dataset as `result FEN` lines
                       (round-trips into --data)
  --shuffle            Fisher-Yates shuffle of the loaded dataset (seeded)
  --test-split F       hold out fraction F in (0,1) as a test set and
                       report train AND test loss before/after tuning
  --iterations N       SPSA iterations (default 400)
  --subset LIST        comma-separated param prefixes: material, mobility,
                       pst, pawns, passed, king, activity, threats, space,
                       phase, bishop_pair (default: all 864)
  --in FILE            baseline eval params TOML (default: built-in baseline)
  --out FILE           export the best parameter set here (default tuned.toml)
  --checkpoint-every N write a checkpoint TOML every N iterations (0 = off)
  --checkpoints-dir D  checkpoint directory (default checkpoints)
  --gain F             SPSA step gain a (default 5.0)
  --perturbation F     SPSA perturbation c (default 2.0)
  --hash MB            TT size per self-play searcher (default 16)
  --smoke              short preset: <=8 games, depth <=4, <=300 iterations
  --compare A B        diff two parameter files (group summary + every
                       differing value) and exit without tuning
  --help               this text

Dataset: without --data/--pgn the dataset is generated by seeded
baseline-vs-baseline self-play; with them the files are loaded instead
(deterministically shufflable and splittable via --shuffle/--test-split).

The pipeline is fully deterministic for a seed: same seed -> same dataset,
same SPSA trajectory, same checkpoint/export files. The run ends with a
regression report of the tuned set (tactics, determinism, eval deltas).
";

struct Flags {
    seed: u64,
    games: usize,
    depth: i32,
    data: Vec<String>,
    pgn: Vec<String>,
    shuffle: bool,
    dump_data: Option<String>,
    test_split: f64,
    iterations: usize,
    subset: Vec<String>,
    in_path: Option<String>,
    out: String,
    checkpoint_every: usize,
    checkpoints_dir: String,
    gain: f64,
    perturbation: f64,
    hash: usize,
    smoke: bool,
}

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    if let Err(e) = run(&args) {
        eprintln!("tune: {e:#}");
        eprintln!("{USAGE}");
        std::process::exit(2);
    }
}

fn parse(args: &[String]) -> anyhow::Result<Flags> {
    let mut f = Flags {
        seed: 1,
        games: 8,
        depth: 4,
        data: Vec::new(),
        pgn: Vec::new(),
        shuffle: false,
        dump_data: None,
        test_split: 0.0,
        iterations: 400,
        subset: Vec::new(),
        in_path: None,
        out: "tuned.toml".to_string(),
        checkpoint_every: 0,
        checkpoints_dir: "checkpoints".to_string(),
        gain: 5.0,
        perturbation: 2.0,
        hash: 16,
        smoke: false,
    };
    let mut i = 0;
    while i < args.len() {
        let flag = args[i].clone();
        match flag.as_str() {
            "--help" | "-h" => {
                print!("{USAGE}");
                std::process::exit(0);
            }
            "--smoke" => {
                f.smoke = true;
                i += 1;
            }
            "--shuffle" => {
                f.shuffle = true;
                i += 1;
            }
            _ => {
                let v = flag_value(args, &mut i, &flag)
                    .with_context(|| format!("unexpected argument: {flag} (use --help)"))?;
                match flag.as_str() {
                    "--seed" => f.seed = v.parse().context("--seed must be an integer")?,
                    "--games" => f.games = v.parse().context("--games must be an integer")?,
                    "--depth" => f.depth = v.parse().context("--depth must be an integer")?,
                    "--data" => f.data.push(v),
                    "--pgn" => f.pgn.push(v),
                    "--dump-data" => f.dump_data = Some(v),
                    "--test-split" => {
                        f.test_split = v.parse().context("--test-split must be a number")?
                    }
                    "--iterations" => {
                        f.iterations = v.parse().context("--iterations must be an integer")?
                    }
                    "--subset" => {
                        f.subset = v
                            .split(',')
                            .map(str::trim)
                            .filter(|s| !s.is_empty())
                            .map(str::to_string)
                            .collect()
                    }
                    "--in" => f.in_path = Some(v),
                    "--out" => f.out = v,
                    "--checkpoint-every" => {
                        f.checkpoint_every =
                            v.parse().context("--checkpoint-every must be an integer")?
                    }
                    "--checkpoints-dir" => f.checkpoints_dir = v,
                    "--gain" => f.gain = v.parse().context("--gain must be a number")?,
                    "--perturbation" => {
                        f.perturbation = v.parse().context("--perturbation must be a number")?
                    }
                    "--hash" => f.hash = v.parse().context("--hash must be an integer (MB)")?,
                    other => bail!("unknown argument: {other}"),
                }
            }
        }
    }
    let file_dataset = !f.data.is_empty() || !f.pgn.is_empty();
    if !file_dataset && f.games == 0 {
        bail!("--games must be >= 1");
    }
    if !file_dataset && f.depth < 1 {
        bail!("--depth must be >= 1");
    }
    if f.test_split != 0.0 && !(0.0 < f.test_split && f.test_split < 1.0) {
        bail!("--test-split must be 0 (off) or in (0, 1)");
    }
    if f.iterations == 0 {
        bail!("--iterations must be >= 1");
    }
    if f.gain <= 0.0 || f.perturbation <= 0.0 {
        bail!("--gain and --perturbation must be positive");
    }
    // The smoke preset clamps the heavy knobs so a mistyped huge run cannot
    // accidentally start; explicit small values are simply kept.
    if f.smoke {
        f.games = f.games.min(8);
        f.depth = f.depth.min(4);
        f.iterations = f.iterations.min(300);
        if f.checkpoint_every == 0 {
            f.checkpoint_every = 50;
        }
    }
    Ok(f)
}

fn run(args: &[String]) -> anyhow::Result<()> {
    // `--compare A B` is a standalone mode: no dataset, no tuning.
    if args.first().map(String::as_str) == Some("--compare") {
        return compare_params(args);
    }
    let f = parse(args)?;

    // --- baseline --------------------------------------------------------
    let baseline = match &f.in_path {
        Some(p) => EvalParams::load(p).with_context(|| format!("cannot load {p:?}"))?,
        None => EvalParams::default(),
    };
    let baseline_src = f.in_path.as_deref().unwrap_or("built-in baseline");
    eprintln!(
        "baseline: {baseline_src} ({} params)",
        baseline.param_count()
    );

    // --- dataset ----------------------------------------------------------
    // Two sources, both deterministic: seeded baseline-vs-baseline
    // self-play (generation), or file loading (--data/--pgn).
    let file_dataset = !f.data.is_empty() || !f.pgn.is_empty();
    let ds = if file_dataset {
        let mut ds = DataSet::empty("");
        for p in &f.data {
            ds.extend(DataSet::from_fen_file(p)?);
        }
        for p in &f.pgn {
            ds.extend(DataSet::from_pgn_file(p)?);
        }
        if f.shuffle {
            let s = f.seed ^ 0x5eed_5eed_5eed;
            ds.shuffle_with(&mut SplitMix64(s));
            eprintln!("dataset: shuffled with seed {s}");
        }
        ds
    } else {
        let sp_cfg = SelfPlayConfig {
            depth: f.depth,
            max_plies: 240,
            hash_mb: f.hash,
            adjudicate_mate: true,
            threads: 1,
        };
        let mut rng = SplitMix64(f.seed);
        let mut games = Vec::with_capacity(f.games);
        for i in 0..f.games {
            let g = play_game_with(&baseline, &baseline, &sp_cfg, &mut rng);
            eprintln!(
                "dataset game {:3}/{:3}: {}  opening {}  plies {}",
                i + 1,
                f.games,
                g.outcome.to_pgn(),
                g.opening,
                g.moves.len()
            );
            games.push(g);
        }
        DataSet::from_selfplay_games(&games).with_seed(f.seed)
    };
    if ds.is_empty() {
        bail!("empty dataset — check --data/--pgn paths or increase --games");
    }
    eprintln!(
        "dataset: {} entries from {} (seed {})",
        ds.len(),
        ds.source,
        f.seed
    );
    eprintln!("stats:   {}", ds.stats());

    // Optional export: write every entry as `result FEN` so the dataset can
    // be re-loaded (and shuffled/split) through the --data path.
    if let Some(p) = &f.dump_data {
        let mut text = String::with_capacity(ds.len() * 96);
        text.push_str("# Morstilia tune dataset: `<result> <FEN>` per line\n");
        for e in &ds.entries {
            text.push_str(&format!("{} {}\n", e.result, e.pos.fen()));
        }
        fs::write(p, &text).with_context(|| format!("cannot write {p:?}"))?;
        eprintln!("dataset: dumped {} entries -> {p}", ds.len());
    }

    // --- deterministic train/test split ------------------------------------
    let (train, test) = if f.test_split > 0.0 {
        let (tr, te) = ds.train_test_split(f.test_split, f.seed);
        eprintln!(
            "split:   train {} / test {} (fraction {}, seed {})",
            tr.len(),
            te.len(),
            f.test_split,
            f.seed
        );
        eprintln!("train:   {}", tr.stats());
        eprintln!("test:    {}", te.stats());
        (tr, te)
    } else {
        (ds.clone(), DataSet::empty(""))
    };

    // --- SPSA --------------------------------------------------------------
    let subset_prefixes: Vec<&str> = f.subset.iter().map(String::as_str).collect();
    let subset = ParamSubset::from_prefixes(&subset_prefixes);
    let cfg = SpsaConfig {
        a: f.gain,
        c: f.perturbation,
        iterations: f.iterations,
        ..SpsaConfig::default()
    };
    eprintln!(
        "subset: {} ({} params selected)",
        if subset.is_all() {
            "all".to_string()
        } else {
            f.subset.join(",")
        },
        subset.selected_count()
    );
    if f.checkpoint_every > 0 {
        fs::create_dir_all(&f.checkpoints_dir)
            .with_context(|| format!("cannot create {:?}", f.checkpoints_dir))?;
    }

    // SPSA randomness is derived from the same --seed (self-play and file
    // shuffling use their own derived streams, so this is a fresh one).
    let mut rng = SplitMix64(f.seed ^ 0x59a5_5a59);
    let mut ckpt_err: Option<anyhow::Error> = None;
    let report = tune_with_callback(
        &baseline,
        &train,
        &subset,
        &cfg,
        &mut rng,
        |k, loss, best| {
            let it = k + 1;
            let want_checkpoint =
                f.checkpoint_every > 0 && (it % f.checkpoint_every == 0 || it == f.iterations);
            if want_checkpoint {
                let path = format!("{}/tuned_it{:06}.toml", f.checkpoints_dir, it);
                if let Err(e) = best.save(&path) {
                    ckpt_err = Some(e);
                    return;
                }
                eprintln!("checkpoint {:>6}: best loss {loss:.6} -> {path}", it);
            }
            if it % 100 == 0 || it == f.iterations {
                eprintln!("iteration {:>6}: best loss {loss:.6}", it);
            }
        },
    );
    if let Some(e) = ckpt_err {
        return Err(e);
    }

    // --- best set + export --------------------------------------------------
    let mut best_ev = baseline.clone();
    best_ev.from_vec(&report.best_params);
    best_ev
        .save(&f.out)
        .with_context(|| format!("cannot export tuned params to {:?}", f.out))?;

    let drop = report.loss_before - report.loss_best;
    println!(
        "spsa: {} iterations  loss {:.6} -> {:.6} (best, {:.1}% improvement)  final {:.6}",
        report.iterations_run,
        report.loss_before,
        report.loss_best,
        report.relative_improvement() * 100.0,
        report.loss_final
    );
    if !test.is_empty() {
        // Holdout: the honest generalisation signal (never trained on).
        let before = test.texel_loss(&baseline);
        let after = test.texel_loss(&best_ev);
        println!(
            "holdout: test loss {before:.6} -> {after:.6} ({} entries, {} better)",
            test.len(),
            if after <= before {
                "yes"
            } else {
                "NO — overfit"
            }
        );
    }
    println!(
        "tuning: updated {} of {} params  exported -> {}",
        report.updated_count,
        subset.selected_count(),
        f.out
    );

    // --- regression protection ---------------------------------------------
    let reg = run_regression(&baseline, &best_ev);
    for c in &reg.cases {
        println!(
            "regression {:<14} best {:<5} tactic {} deterministic {} nodes ({}, {})  eval {:>4} -> {:>4}",
            c.name,
            c.tuned_best,
            if c.tactic_ok { "ok" } else { "FAIL" },
            if c.deterministic { "ok" } else { "FAIL" },
            c.nodes.0,
            c.nodes.1,
            c.baseline_eval,
            c.tuned_eval,
        );
    }
    println!(
        "regression summary: tactics {} determinism {} max eval delta {} cp avg {:.1} cp",
        if reg.all_tactics_ok { "ok" } else { "FAIL" },
        if reg.all_deterministic { "ok" } else { "FAIL" },
        reg.max_eval_delta,
        reg.avg_eval_delta,
    );
    println!(
        "loss drop: {drop:.4} over the training set  ({} entries, seed {})",
        train.len(),
        f.seed
    );
    Ok(())
}

/// Reads `--name value` or `--name=value` starting at `*i`, advancing past
/// the consumed tokens. Returns `None` when the next token is not `name`.
fn flag_value(args: &[String], i: &mut usize, name: &str) -> Option<String> {
    let arg = args.get(*i)?;
    if let Some(v) = arg.strip_prefix(&format!("{name}=")) {
        *i += 1;
        return Some(v.to_string());
    }
    if arg == name {
        *i += 1;
        let v = args.get(*i).cloned();
        *i += usize::from(v.is_some());
        return v;
    }
    None
}

/// `--compare A B`: loads both parameter files and prints a per-group
/// summary followed by every differing value (`name A -> B (+delta)`).
/// Standalone mode — no dataset, no tuning; the "original vs tuned" review
/// tool required alongside every export.
fn compare_params(args: &[String]) -> anyhow::Result<()> {
    let a = args.get(1).context("--compare needs two parameter files")?;
    let b = args.get(2).context("--compare needs two parameter files")?;
    if args.len() > 3 {
        bail!("unexpected argument: {} (usage: --compare A B)", args[3]);
    }
    let pa = EvalParams::load(a).with_context(|| format!("cannot load {a:?}"))?;
    let pb = EvalParams::load(b).with_context(|| format!("cannot load {b:?}"))?;
    let defs = EvalParams::bounds();
    let va = pa.to_vec();
    let vb = pb.to_vec();
    if va.len() != defs.len() || vb.len() != defs.len() {
        bail!(
            "parameter vector size mismatch ({} vs {}, {} in bounds)",
            va.len(),
            vb.len(),
            defs.len()
        );
    }

    use std::collections::BTreeMap;
    // group -> (changed count, max |delta|, sum |delta|)
    let mut groups: BTreeMap<&str, (usize, f64, f64)> = BTreeMap::new();
    let mut details: Vec<String> = Vec::new();
    let mut n_changed = 0usize;
    let mut max_delta = 0.0f64;
    let mut sum_abs = 0.0f64;
    for i in 0..defs.len() {
        if va[i] == vb[i] {
            continue;
        }
        let delta = vb[i] - va[i];
        let abs = delta.abs();
        n_changed += 1;
        max_delta = max_delta.max(abs);
        sum_abs += abs;
        let group = defs[i].name.split('.').next().unwrap_or("?");
        let e = groups.entry(group).or_insert((0, 0.0, 0.0));
        e.0 += 1;
        e.1 = e.1.max(abs);
        e.2 += abs;
        details.push(format!(
            "  {:<26} {} -> {} ({:+})",
            defs[i].name,
            fmt_param(va[i]),
            fmt_param(vb[i]),
            delta
        ));
    }

    println!("compare: {a} vs {b}");
    if n_changed == 0 {
        println!(
            "identical: {} / {} parameters match",
            defs.len(),
            defs.len()
        );
        return Ok(());
    }
    println!("group summary:");
    for (group, (n, mx, sm)) in &groups {
        println!("  {group:<14} changed {n:>4}  max |d| {mx:>6.1}  sum |d| {sm:>7.1}");
    }
    for line in &details {
        println!("{line}");
    }
    println!(
        "changed: {n_changed} / {} parameters  max |d| {max_delta:.1}  mean |d| {:.1}",
        defs.len(),
        sum_abs / n_changed as f64
    );
    Ok(())
}

/// Formats a parameter value without a trailing `.0` for integers.
fn fmt_param(v: f64) -> String {
    if v.fract() == 0.0 {
        format!("{}", v as i64)
    } else {
        format!("{v}")
    }
}
